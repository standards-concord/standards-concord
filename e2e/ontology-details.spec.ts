import { test, expect, settle, signIn, uniq } from './fixtures';

test('a steward edits listing details and sees them on the Overview, hub and masthead; a contributor cannot edit', async ({ page, consoleGuard }) => {
  await signIn(page, { name: `Details steward ${uniq()}`, role: 'steward' });
  await page.goto('/');
  await page.getByRole('button', { name: 'New ontology', exact: true }).click();
  const create = page.getByRole('dialog', { name: 'New ontology', exact: true });
  const original = `Original details ${uniq()}`;
  await create.getByLabel('Title').fill(original);
  await create.getByLabel('Description').fill('The original description.');
  await create.getByLabel('Subject area').fill('Original subject');
  await create.getByRole('button', { name: 'Create ontology', exact: true }).click();
  await expect(page).toHaveURL(/\/o\/ont_[^/]+$/);
  const id = page.url().split('/o/')[1];
  const ownerCookies = await page.context().cookies();
  await page.getByRole('button', { name: 'Ontology details', exact: true }).click();
  await page.getByRole('button', { name: 'Edit details', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Edit details', exact: true });
  await expect(edit.getByText('This changes how the standard is listed in Concord. The title and description inside the ontology file change through a change request.', { exact: true })).toBeVisible();
  const save = edit.getByRole('button', { name: 'Save details', exact: true });
  await expect(save).toBeDisabled();
  await edit.getByLabel('Title').fill('   ');
  await expect(save).toBeDisabled();
  const title = `Clearer details ${uniq()}`;
  const description = `A clearer description ${uniq()}.`;
  await edit.getByLabel('Title').fill(title);
  await edit.getByLabel('Description').fill(description);
  await edit.getByLabel('Subject area').fill('');
  // A refused save keeps the form and explains the error inline, so it can be corrected or retried.
  consoleGuard.allow(/Failed to load resource: the server responded with a status of 400/);
  await page.route(`**/api/ontologies/${id}`, (route) => route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ error: 'Could not save this title. Try again.' }) }), { times: 1 });
  await save.click();
  await expect(edit.getByText('Could not save this title. Try again.', { exact: true })).toBeVisible();
  await expect(edit.getByLabel('Title')).toHaveValue(title);
  await save.click();
  await expect(edit).toHaveCount(0);
  await expect(page.getByRole('heading', { level: 1, name: title, exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'About this ontology' })).toContainText(description);
  await expect(page.getByRole('combobox', { name: 'Switch ontology', exact: true }).getByRole('option', { name: title, exact: true })).toHaveCount(1);
  await expect(page.getByRole('combobox', { name: 'Switch ontology', exact: true }).getByRole('option', { name: original, exact: true })).toHaveCount(0);
  // Client-side navigation keeps the same provider and its browser cache alive.
  await page.getByRole('link', { name: 'Concord: home', exact: true }).click();
  const card = page.getByRole('link', { name: new RegExp(`^${title}`) });
  await expect(card).toBeVisible();
  await expect(card).toContainText(description);
  await card.click();
  await page.setViewportSize({ width: 390, height: 950 });
  await page.getByRole('button', { name: 'Ontology details', exact: true }).click();
  await page.getByRole('button', { name: 'Edit details', exact: true }).click();
  await expect(edit.getByLabel('Title')).toHaveValue(title);
  await expect(edit.getByLabel('Description')).toHaveValue(description);
  await expect(edit.getByLabel('Subject area')).toHaveValue('');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await edit.getByLabel('Title').fill(`Cancelled ${uniq()}`);
  await edit.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1, name: title, exact: true })).toBeVisible();

  const contributor = await signIn(page, { name: `Details contributor ${uniq()}`, role: 'contributor' });
  const contributorCookies = await page.context().cookies();
  await page.context().clearCookies();
  await page.context().addCookies(ownerCookies);
  expect((await page.request.put(`/api/ontologies/${id}/members/${contributor.user.id}`, { data: { roles: ['contributor'] } })).ok()).toBeTruthy();
  await page.context().clearCookies();
  await page.context().addCookies(contributorCookies);
  await page.goto(`/o/${id}`);
  await settle(page);
  await page.getByRole('button', { name: 'Ontology details', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit details', exact: true })).toHaveCount(0);
  expect((await page.request.patch(`/api/ontologies/${id}`, { data: { title: 'Refused' } })).status()).toBe(403);
  await page.reload();
  await expect(page.getByRole('heading', { level: 1, name: title, exact: true })).toBeVisible();
});
