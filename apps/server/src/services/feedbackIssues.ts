import { createHash, randomBytes, timingSafeEqual } from 'node:crypto';
import { PUBLIC_NOTICE_VERSION, publicSummary, type FeedbackPublicationState, type FeedbackPublicationStatus } from '@concord/shared';
import { config } from '../config.js';
import { get, HttpError, list, put, transaction } from '../db.js';
import { newId } from '../ids.js';

/**
 * Opt-in public feedback summaries, filed as GitHub issues.
 *
 * Nothing a tester says is published unless they tick "post a public summary"
 * and write a short summary, which they see exactly as it will be posted. Only
 * that summary is sent, with a random publication id.
 *
 * One record per submission (keyed by the feedback id), one issue per record.
 * The destination repository is fixed when the tester consents. Every change
 * to a record is a fenced transition: a worker holds a claim id and may only
 * change the record while it still holds that claim, and `withdrawn` is
 * terminal. Just before every request the worker re-checks, in the same
 * transaction that authorises it, that the record is still in the state it
 * expects, that the feedback still exists and that the queue isn't paused.
 *
 * Nothing is ever matched on content. If a POST's outcome is unknown, the
 * worker never posts again and never adopts an issue on its own: it lists
 * candidate issues for an administrator, who says which one is ours (or that
 * none is). The triage routine posts its comments and labels through this
 * server (see triagePublication), which records each comment's id the moment
 * GitHub returns it; withdrawal deletes exactly those ids and nothing else.
 */

export const FEEDBACK_LABELS = ['feedback', 'needs-triage'];
/** Labels the triage routine may choose from; the server applies them. */
export const TRIAGE_KINDS = ['bug', 'enhancement', 'ux', 'docs', 'question', 'insight'] as const;
export const TRIAGE_SIZES = ['size:small', 'size:large'] as const;
export const TRIAGE_FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
export const marker = (pubId: string) => `<!-- concord-feedback-publication: ${pubId} -->`;

type Issue = NonNullable<FeedbackPublicationStatus['issue']>;

export interface Publication {
  /** The feedback id. */
  id: string;
  /** Random id used in the issue's marker, so the issue doesn't reveal the feedback id. */
  pubId: string;
  /** Destination, fixed at consent. */
  repo: string;
  /** Exactly what the tester saw and agreed to. */
  summary: string;
  noticeVersion: number;
  withdrawHash: string;
  state: FeedbackPublicationState;
  /** The worker currently allowed to change this record, and until when. */
  claim?: string;
  claimUntil?: number;
  attempts: number;
  /** Wall-clock ms (not the demo's governance clock). */
  nextAttemptAt: number;
  /** Set in the transaction that authorises a POST: the issue may exist from here on. */
  sentAt?: number;
  /** The issue, recorded from GitHub's answer or by an administrator; never inferred from a search. */
  issue?: Issue;
  /** After an unknown outcome: issues an administrator may pick from. Shown, never adopted automatically. */
  candidates?: Issue[];
  /** Withdrawal progress, saved as it goes: the issue has been replaced and closed. */
  patched?: boolean;
  /** Ids of the triage comments this server posted on the issue and hasn't deleted yet. */
  comments?: number[];
  /** A triage comment may have been posted without its id being recorded: a fresh id for each such uncertainty. */
  commentUnknown?: string;
  /** Triage in progress through this server: no withdrawal finishes while a comment is being posted. */
  triage?: { claim: string; until: number; phase: 'commenting' | 'labelling' };
  /** The routine's decision, saved before anything is written, so a retry carries out the same one. */
  decision?: TriageDecision;
  /** Taken out of the triage queue because GitHub said the issue isn't open or labelled for triage. */
  triageParked?: { reason: string; at: string };
  triagedAt?: string;
  /** A withdrawal that needs an administrator (which issue, or a comment that may exist). */
  adminNeeded?: boolean;
  /** Why it's waiting for an administrator, or the last error. */
  lastError?: string;
  createdAt: string;
}

interface Kv<T> {
  id: string;
  value: T;
}

export const MAX_ATTEMPTS = 8;
const LEASE_MS = 2 * 60_000;
const HOUR_MS = 60 * 60_000;
const TITLE_MAX = 80;
const ACTIVE: FeedbackPublicationState[] = ['queued', 'sending', 'unknown', 'withdrawing'];

/* -------------------------------- time ---------------------------------- */

let nowFn = () => Date.now();
const now = () => nowFn();
/** Test hook: control wall-clock time. */
export function setNow(fn?: () => number) {
  nowFn = fn ?? (() => Date.now());
}

/* ------------------------------- config --------------------------------- */

const validRepo = (r: string) => /^[\w.-]+\/[\w.-]+$/.test(r);
export const issuesEnabled = () => !!config.feedbackIssues.token && validRepo(config.feedbackIssues.repo);
const safeError = (msg: string) => (config.feedbackIssues.token ? msg.split(config.feedbackIssues.token).join('***') : msg).slice(0, 300);
const sha = (s: string) => createHash('sha256').update(s).digest('hex');
const validId = (v: unknown): v is number => Number.isSafeInteger(v) && (v as number) > 0;
const uncertainty = () => randomBytes(9).toString('hex');

/* ------------------------------ rendering ------------------------------- */

/** Every ASCII punctuation character GitHub could read as Markdown, an HTML tag or a character reference. */
const escapeMarkdown = (s: string) =>
  s
    .replace(/([\\`*_{}[\]()#+!|<>~=&$:^-])/g, '\\$1')
    // "1." at the start of a line would start a numbered list.
    .replace(/^(\s*\d+)\./gm, '$1\\.');

export function issueTitle(summary: string): string {
  const first = summary.split('\n')[0].trim();
  return `Feedback: ${first.length > TITLE_MAX ? `${first.slice(0, TITLE_MAX - 1).trimEnd()}…` : first}`;
}

export function issueBody(pub: Pick<Publication, 'pubId' | 'summary'>): string {
  return [
    marker(pub.pubId),
    '_A tester of Concord chose to post this summary publicly. It is exactly what they wrote and reviewed; nothing else from their feedback is included._',
    '',
    ...pub.summary.split('\n').map((l) => `> ${escapeMarkdown(l)}`),
  ].join('\n');
}

/* ------------------------------ consent --------------------------------- */

export function checkPublicSummary(summary: unknown): asserts summary is string {
  if (!issuesEnabled()) throw new HttpError(409, 'Posting feedback publicly is not switched on');
  if (typeof summary !== 'string' || !summary.trim()) throw new HttpError(400, 'Write a short summary to post, or untick the option');
  if (publicSummary(summary) !== summary) throw new HttpError(400, 'The summary changed when links and contact details were removed. Check the preview and send it again.');
}

/** Record the tester's consent and queue their summary. Returns the token that lets them withdraw it. */
export function queuePublication(feedbackId: string, summary: string): FeedbackPublicationStatus {
  checkPublicSummary(summary);
  const token = randomBytes(24).toString('base64url');
  const pub: Publication = {
    id: feedbackId,
    pubId: newId('pub'),
    repo: config.feedbackIssues.repo,
    summary,
    noticeVersion: PUBLIC_NOTICE_VERSION,
    withdrawHash: sha(token),
    state: 'queued',
    attempts: 0,
    nextAttemptAt: now(),
    createdAt: new Date(now()).toISOString(),
  };
  transaction(() => {
    if (get('feedbackPublications', feedbackId)) throw new HttpError(409, 'This feedback already has a public summary');
    put('feedbackPublications', pub);
  });
  return { ...status(pub), withdrawToken: token };
}

export const publicationFor = (feedbackId: string) => get<Publication>('feedbackPublications', feedbackId);

export function status(pub: Publication): FeedbackPublicationStatus {
  return { state: pub.state, issue: pub.state === 'filed' ? pub.issue : undefined };
}

/* ------------------------------- GitHub --------------------------------- */

class GitHubError extends Error {
  constructor(
    message: string,
    /** The request may have taken effect (timeout, dropped connection, 5xx). */
    readonly ambiguous: boolean,
    readonly rateLimited = false,
    /** Wall-clock time GitHub asked us to wait until, if it said. */
    readonly retryAt?: number,
    readonly status?: number,
  ) {
    super(message);
  }
}

async function github(method: string, path: string, body?: unknown): Promise<unknown> {
  const { apiUrl, token } = config.feedbackIssues;
  let res: Response;
  try {
    res = await fetch(`${apiUrl}${path}`, {
      method,
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'concord-feedback',
        ...(body ? { 'Content-Type': 'application/json' } : {}),
      },
      body: body ? JSON.stringify(body) : undefined,
      signal: AbortSignal.timeout(15_000),
    });
  } catch (err) {
    throw new GitHubError(`GitHub request failed: ${(err as Error).message}`, true);
  }
  if (res.ok) {
    if (res.status === 204) return undefined;
    // GitHub did the work but we may not learn its result: that's as unknown as a dropped connection.
    try {
      return await res.json();
    } catch (err) {
      throw new GitHubError(`GitHub’s answer was cut off: ${(err as Error).message}`, true);
    }
  }
  // https://docs.github.com/en/rest/using-the-rest-api/best-practices-for-using-the-rest-api#handle-rate-limit-errors-appropriately
  const retryAfter = Number(res.headers.get('retry-after'));
  const reset = Number(res.headers.get('x-ratelimit-reset'));
  // Secondary limits can come as a 403 with quota left and no Retry-After; their message says so.
  const text = res.status === 403 || res.status === 429 ? await res.text().catch(() => '') : '';
  const limited = res.status === 429 || (res.status === 403 && (res.headers.get('x-ratelimit-remaining') === '0' || res.headers.has('retry-after') || /rate limit|abuse detection/i.test(text)));
  const retryAt = limited ? (retryAfter > 0 ? now() + retryAfter * 1000 : res.headers.get('x-ratelimit-remaining') === '0' && reset > 0 ? reset * 1000 : undefined) : undefined;
  throw new GitHubError(`GitHub answered ${res.status}`, res.status >= 500, limited, retryAt, res.status);
}

let login: string | undefined;
/** The account the token belongs to. */
async function botLogin(): Promise<string> {
  login ??= ((await github('GET', '/user')) as { login: string }).login;
  return login;
}

/**
 * After an unknown outcome: issues an administrator might recognise as ours,
 * from those the token's account created since just before the send. Only a
 * hint for a person to check; nothing is done with these automatically.
 */
async function findCandidates(pub: Publication): Promise<{ candidates: Issue[]; note?: string }> {
  const me = await botLogin();
  const from = (pub.sentAt ?? now()) - 10 * 60_000;
  const candidates: Issue[] = [];
  for (let page = 1; page <= 5; page++) {
    await waitForPause(pub.repo);
    const issues = (await github('GET', `/repos/${pub.repo}/issues?creator=${encodeURIComponent(me)}&state=all&sort=created&direction=desc&per_page=100&page=${page}`)) as {
      number: number;
      html_url: string;
      title?: string;
      body?: string;
      created_at?: string;
    }[];
    for (const i of issues) {
      if (i.created_at && Date.parse(i.created_at) < from) continue;
      if (i.body?.includes(marker(pub.pubId)) || i.title === issueTitle(pub.summary)) candidates.push({ number: i.number, url: i.html_url });
    }
    const oldest = issues.at(-1)?.created_at;
    if (issues.length < 100 || (oldest && Date.parse(oldest) < from)) return { candidates };
  }
  return { candidates, note: 'Only the newest 500 issues were checked.' };
}

/* -------------------------- pause and rate cap -------------------------- */

interface Pause {
  until: number;
  /** Consecutive rate-limit responses, for exponential backoff when GitHub gives no time. */
  streak: number;
}
const pauseId = (repo: string) => `feedback-issues:pause:${repo.toLowerCase()}`;
const rateId = (repo: string) => `feedback-issues:rate:${repo.toLowerCase()}`;
const pauseOf = (repo: string) => get<Kv<Pause>>('kv', pauseId(repo))?.value ?? { until: 0, streak: 0 };

class Paused extends Error {
  constructor(readonly until: number) {
    super('paused');
  }
}

/** Before every request: stop if GitHub has asked the whole queue to wait. */
async function waitForPause(repo: string) {
  const p = pauseOf(repo);
  if (p.until > now()) throw new Paused(p.until);
}

function rateLimited(repo: string, retryAt: number | undefined): number {
  return transaction(() => {
    const p = pauseOf(repo);
    const streak = p.streak + 1;
    const until = Math.max(p.until, retryAt ?? now() + Math.min(60_000 * 2 ** (streak - 1), HOUR_MS));
    put('kv', { id: pauseId(repo), value: { until, streak } });
    return until;
  });
}

function rateOk(repo: string) {
  const p = pauseOf(repo);
  if (p.streak) put('kv', { id: pauseId(repo), value: { until: p.until, streak: 0 } });
}

/** Take one slot in the rolling hour, inside the caller's transaction. Returns when one frees up if full. */
function takeSlot(repo: string): number | undefined {
  const t = now();
  const recent = (get<Kv<number[]>>('kv', rateId(repo))?.value ?? []).filter((x) => x > t - HOUR_MS);
  if (recent.length >= config.feedbackIssues.perHour) return Math.min(...recent) + HOUR_MS;
  put('kv', { id: rateId(repo), value: [...recent, t] });
  return undefined;
}

/* --------------------------- fenced transitions ------------------------- */

/** Change a record only while `claim` still holds it and it isn't withdrawn. */
function fenced(id: string, claim: string, change: (p: Publication) => Partial<Publication> | undefined): Publication | undefined {
  return transaction(() => {
    const p = get<Publication>('feedbackPublications', id);
    if (!p || p.claim !== claim || p.state === 'withdrawn') return undefined;
    const c = change(p);
    if (!c) return undefined;
    const next = { ...p, ...c };
    put('feedbackPublications', next);
    return next;
  });
}

const release = { claim: undefined, claimUntil: undefined };

function acquire(id: string): { pub: Publication; claim: string } | undefined {
  return transaction(() => {
    const p = get<Publication>('feedbackPublications', id);
    const t = now();
    if (!p || !ACTIVE.includes(p.state) || p.adminNeeded || p.nextAttemptAt > t) return undefined;
    if (p.claim && (p.claimUntil ?? 0) > t) return undefined;
    if (pauseOf(p.repo).until > t) return undefined;
    const claim = randomBytes(12).toString('hex');
    // A send whose worker vanished: the issue may exist.
    const state: FeedbackPublicationState = p.state === 'sending' ? 'unknown' : p.state;
    const next: Publication = { ...p, state, claim, claimUntil: t + LEASE_MS };
    // Deleted feedback: never post; take back anything that may have been posted.
    if (!get('feedback', p.id) && state !== 'withdrawing') {
      if (state === 'queued') {
        put('feedbackPublications', { ...p, ...release, state: 'withdrawn', lastError: 'feedback deleted' });
        return undefined;
      }
      next.state = 'withdrawing';
    }
    put('feedbackPublications', next);
    return { pub: next, claim };
  });
}

const backoff = (attempts: number) => Math.min(5 * 60_000 * 2 ** Math.max(0, attempts - 1), 6 * HOUR_MS);

/* -------------------------------- worker -------------------------------- */

const running = new Map<string, Promise<void>>();

/** Work one record as far as it can go now. Never throws. */
export function processPublication(id: string): Promise<void> {
  const existing = running.get(id);
  if (existing) return existing;
  let done!: () => void;
  const p = new Promise<void>((r) => (done = r));
  running.set(id, p);
  void (async () => {
    try {
      if (issuesEnabled()) for (let i = 0; i < 3 && (await step(id)); i++);
    } catch (err) {
      console.warn(`[feedback] ${safeError((err as Error).message)}`);
    } finally {
      running.delete(id);
      done();
    }
  })();
  return p;
}

/** One claimed step. Returns true if there may be more to do straight away. */
async function step(id: string): Promise<boolean> {
  const got = acquire(id);
  if (!got) return false;
  const { claim } = got;
  let pub = got.pub;
  try {
    if (pub.state === 'withdrawing') return await retractStep(pub, claim);
    if (pub.state === 'unknown') {
      // Never adopt or repost on our own: list what might be ours and ask an administrator.
      const found = await findCandidates(pub);
      rateOk(pub.repo);
      fenced(id, claim, (p) => askAdmin(p, found.candidates, `GitHub’s answer to the post was lost. Say which issue is this summary’s, or that none is.${found.note ? ` ${found.note}` : ''}`));
      return false;
    }
    // queued: authorise the POST in one transaction, re-checking everything that could have changed.
    let wait: number | undefined;
    const authorised = fenced(id, claim, (p) => {
      if (p.state !== 'queued' || !get('feedback', p.id)) return undefined;
      const t = now();
      if (pauseOf(p.repo).until > t) {
        wait = pauseOf(p.repo).until;
        return undefined;
      }
      wait = takeSlot(p.repo);
      if (wait) return undefined;
      return { state: 'sending', sentAt: t, attempts: p.attempts + 1, claimUntil: t + LEASE_MS };
    });
    if (!authorised) {
      fenced(id, claim, (p) => (p.state === 'queued' ? { ...release, nextAttemptAt: wait ?? now() } : { ...release, nextAttemptAt: now() }));
      return !wait;
    }
    pub = authorised;
    const created = (await github('POST', `/repos/${pub.repo}/issues`, { title: issueTitle(pub.summary), body: issueBody(pub), labels: FEEDBACK_LABELS })) as { number?: unknown; html_url?: unknown } | null;
    if (!validId(created?.number) || typeof created?.html_url !== 'string') throw new GitHubError('GitHub’s answer had no issue number', true);
    const issue = { number: created.number, url: created.html_url };
    rateOk(pub.repo);
    const after = fenced(id, claim, (p) => (p.state === 'withdrawing' ? { issue, ...release, nextAttemptAt: now() } : { state: 'filed', issue, lastError: undefined, ...release }));
    return after?.state === 'withdrawing';
  } catch (err) {
    onError(id, claim, pub.repo, err);
    // A lost answer: go straight on to listing candidates for an administrator.
    const after = publicationFor(id);
    return after?.state === 'unknown' && !after.claim && after.nextAttemptAt <= now();
  }
}

/** Hand a record to an administrator: a send with an unknown outcome, or a withdrawal that needs a decision. */
function askAdmin(p: Publication, candidates: Issue[] | undefined, why: string): Partial<Publication> {
  const base = { ...release, candidates, lastError: why, nextAttemptAt: now() };
  return p.state === 'withdrawing' ? { ...base, adminNeeded: true } : { ...base, state: 'needs-admin' };
}

/**
 * Take back a summary that is, or may be, posted, using only ids this server
 * recorded: the issue, then each triage comment it posted. Progress is saved
 * as it goes, so an interrupted withdrawal carries on where it stopped.
 */
async function retractStep(pub: Publication, claim: string): Promise<boolean> {
  const issue = pub.issue;
  if (!issue) {
    if (!pub.sentAt) {
      fenced(pub.id, claim, () => ({ state: 'withdrawn', ...release }));
      return false;
    }
    // Posted, but GitHub's answer was lost: an administrator says which issue it is.
    const found = await findCandidates(pub);
    rateOk(pub.repo);
    fenced(pub.id, claim, (p) => askAdmin(p, found.candidates, `The tester withdrew a summary whose issue number was never recorded. Say which issue it is, or confirm none exists.${found.note ? ` ${found.note}` : ''}`));
    return false;
  }
  if (!pub.patched) {
    await waitForPause(pub.repo);
    await github('PATCH', `/repos/${pub.repo}/issues/${issue.number}`, { title: 'Withdrawn feedback', body: 'The tester withdrew this feedback.', state: 'closed', state_reason: 'not_planned' });
    if (!fenced(pub.id, claim, () => ({ patched: true }))) return false;
  }
  // Triage in progress: wait for it to stop (it sees the withdrawal before its next write).
  // A comment whose worker vanished mid-POST may exist: that stays unknown.
  const cur = publicationFor(pub.id)!;
  if (cur.triage) {
    if (cur.triage.until > now()) {
      fenced(pub.id, claim, () => ({ ...release, nextAttemptAt: cur.triage!.until }));
      return false;
    }
    fenced(pub.id, claim, (p) => ({ triage: undefined, commentUnknown: p.commentUnknown || (p.triage?.phase === 'commenting' ? uncertainty() : undefined) }));
  }
  for (const cid of publicationFor(pub.id)?.comments ?? []) {
    await deleteComment(pub.repo, cid);
    fenced(pub.id, claim, (p) => ({ comments: (p.comments ?? []).filter((x) => x !== cid) }));
  }
  rateOk(pub.repo);
  const after = publicationFor(pub.id)!;
  if (after.commentUnknown) {
    fenced(pub.id, claim, (p) => askAdmin(p, undefined, `A triage comment may have been posted on issue #${issue.number} without its id being recorded. Delete it by hand if it is there, then confirm.`));
    return false;
  }
  fenced(pub.id, claim, () => ({ state: 'withdrawn', adminNeeded: undefined, candidates: undefined, lastError: undefined, ...release }));
  return false;
}

async function deleteComment(repo: string, id: number) {
  await waitForPause(repo);
  try {
    await github('DELETE', `/repos/${repo}/issues/comments/${id}`);
  } catch (err) {
    if (!(err instanceof GitHubError && err.status === 404)) throw err;
  }
}

function onError(id: string, claim: string, repo: string, err: unknown) {
  if (err instanceof Paused) {
    fenced(id, claim, (p) => ({ ...release, state: p.state === 'sending' ? 'unknown' : p.state, nextAttemptAt: err.until }));
    return;
  }
  const e = err instanceof GitHubError ? err : new GitHubError((err as Error).message, true);
  const pausedUntil = e.rateLimited ? rateLimited(repo, e.retryAt) : undefined;
  const p = fenced(id, claim, (p) => {
    const lastError = safeError(e.message);
    // A withdrawal keeps going until it's done; it never falls back to posting.
    if (p.state === 'withdrawing') return { ...release, nextAttemptAt: pausedUntil ?? now() + backoff(p.attempts + 1), attempts: p.attempts + 1, lastError };
    if (p.state === 'sending') {
      // Rate-limited and other definite refusals mean no issue was created; anything else may have created one.
      if (pausedUntil) return { ...release, state: 'queued', sentAt: undefined, attempts: p.attempts - 1, nextAttemptAt: pausedUntil, lastError };
      if (e.ambiguous) return { ...release, state: 'unknown', nextAttemptAt: now(), lastError };
      if (p.attempts >= MAX_ATTEMPTS) return { ...release, state: 'needs-admin', sentAt: undefined, lastError };
      return { ...release, state: 'queued', sentAt: undefined, nextAttemptAt: now() + backoff(p.attempts), lastError };
    }
    // Listing candidates after an unknown outcome failed: ask an administrator anyway, unless only rate-limited.
    if (pausedUntil) return { ...release, nextAttemptAt: pausedUntil, lastError };
    return askAdmin(p, undefined, `GitHub’s answer to the post was lost, and listing possible issues failed (${lastError}). Check GitHub, then say which issue is ours, or that none is.`);
  });
  console.warn(`[feedback] public summary for ${id}: ${safeError(e.message)}${p?.state === 'needs-admin' ? ' (waiting for an administrator)' : ''}`);
}

/** Wait briefly for a record so the tester can be told; it carries on in the background if GitHub is slow. */
export async function processWithin(id: string, ms = 4000): Promise<Publication | undefined> {
  let timer: NodeJS.Timeout | undefined;
  await Promise.race([processPublication(id), new Promise<void>((r) => (timer = setTimeout(r, ms)))]);
  clearTimeout(timer);
  return publicationFor(id);
}

/** Work every record that is due, and take back summaries whose feedback was deleted. Run on a timer. */
export async function processOutstanding(): Promise<void> {
  if (!issuesEnabled()) return;
  for (const p of list<Publication>('feedbackPublications')) {
    // Deleted feedback: withdraw from whatever state it's in (needs-admin included).
    if (p.state !== 'withdrawn' && p.state !== 'withdrawing' && !get('feedback', p.id)) requestWithdrawal(p.id);
    const latest = publicationFor(p.id);
    if (latest && ACTIVE.includes(latest.state)) await processPublication(p.id);
  }
}

/* ----------------------------- withdrawing ------------------------------ */

const tokenMatches = (pub: Publication, token: unknown) => {
  if (typeof token !== 'string' || !token) return false;
  const a = Buffer.from(sha(token));
  const b = Buffer.from(pub.withdrawHash);
  return a.length === b.length && timingSafeEqual(a, b);
};

/** Never posted yet → withdrawn now. Possibly posted → withdrawing, which the worker finishes. */
function requestWithdrawal(id: string) {
  transaction(() => {
    const p = get<Publication>('feedbackPublications', id);
    if (!p || p.state === 'withdrawn' || p.state === 'withdrawing') return;
    const maybePosted = !!p.issue || !!p.sentAt;
    // An in-flight worker keeps its claim; its fenced success or error handler sees "withdrawing".
    put('feedbackPublications', maybePosted ? { ...p, state: 'withdrawing', adminNeeded: undefined, nextAttemptAt: now() } : { ...p, ...release, state: 'withdrawn' });
  });
}

/** The tester takes their public summary back. */
export async function withdrawPublication(feedbackId: string, token: unknown): Promise<FeedbackPublicationStatus> {
  const pub = publicationFor(feedbackId);
  if (!pub || !tokenMatches(pub, token)) throw new HttpError(403, 'That withdrawal link is not valid');
  requestWithdrawal(feedbackId);
  const after = publicationFor(feedbackId)!;
  if (after.state === 'withdrawing') await processWithin(feedbackId);
  return status(publicationFor(feedbackId)!);
}

export type AdminAction = { action: 'check' } | { action: 'adopt'; issue: number } | { action: 'repost' } | { action: 'confirm' } | { action: 'comment'; comment: number };

type AttentionKind = 'post-unknown' | 'withdrawal' | 'comment-unknown' | 'triage-parked';
/**
 * Names exactly what an administrator is deciding about. A decision made on
 * an older view (a stale page, a second tab) carries an older ref and is refused.
 */
export function attentionRef(p: Publication): string {
  return sha(JSON.stringify([attentionKind(p), p.state, p.issue?.number, p.candidates?.map((c) => c.number), p.commentUnknown, p.triageParked?.at, p.lastError, p.adminNeeded, p.sentAt])).slice(0, 16);
}

/** Why a record is waiting for an administrator, if it is. */
function attentionKind(p: Publication): AttentionKind | undefined {
  if (p.state === 'needs-admin') return 'post-unknown';
  if (p.state === 'withdrawing' && p.adminNeeded) return 'withdrawal';
  if (p.state === 'filed' && p.commentUnknown) return 'comment-unknown';
  if (p.state === 'filed' && p.triageParked) return 'triage-parked';
  return undefined;
}

/**
 * Administrators: decide for a record waiting for them.
 * - "check": list candidate issues again.
 * - "adopt": this issue is the summary's (one of the candidates, or one they found).
 * - "repost" (a post with an unknown outcome): none is; post it again.
 * - "confirm" (a withdrawal): nothing of it is left on GitHub; finish.
 * - A triage comment whose outcome is unknown: "comment" records the id of the
 *   one they found on the issue; "confirm" says there is none.
 * - A summary taken out of the triage queue: "check" puts it back.
 */
export async function resolvePublication(id: string, a: AdminAction, ref: string): Promise<FeedbackPublicationStatus> {
  const before = get<Publication>('feedbackPublications', id);
  if (!before || !attentionKind(before)) throw new HttpError(409, 'That public summary isn’t waiting for an administrator');
  if (attentionRef(before) !== ref) throw new HttpError(409, 'That public summary changed since you looked at it; reload and decide again');
  // A recorded comment must really be this server's triage comment on this issue.
  if (a.action === 'comment') await verifyTriageComment(before, a.comment);
  const p = transaction(() => {
    const p = get<Publication>('feedbackPublications', id);
    if (!p) return undefined;
    const k = attentionKind(p);
    if (!k || attentionRef(p) !== ref) return undefined;
    const reset = { ...release, adminNeeded: undefined, lastError: undefined, nextAttemptAt: now() };
    let next: Publication | undefined;
    if (k === 'comment-unknown') {
      // The administrator looked at the issue's comments: one is the triage comment (record it), or none is.
      if (a.action === 'comment') next = { ...p, commentUnknown: undefined, comments: [...new Set([...(p.comments ?? []), a.comment])] };
      else if (a.action === 'confirm') next = { ...p, commentUnknown: undefined };
    } else if (k === 'triage-parked') {
      if (a.action === 'check') next = { ...p, triageParked: undefined };
    } else if (a.action === 'comment') next = undefined;
    else if (a.action === 'check')
      next =
        p.state === 'withdrawing' || p.issue
          ? { ...p, ...reset }
          : p.sentAt
            ? { ...p, ...reset, state: 'unknown' } // list the candidates again
            : { ...p, ...reset, state: 'queued', attempts: 0 }; // refused every time: try posting again
    else if (a.action === 'adopt' && !p.issue) {
      const issue = p.candidates?.find((c) => c.number === a.issue) ?? { number: a.issue, url: `https://github.com/${p.repo}/issues/${a.issue}` };
      next = { ...p, ...reset, issue, candidates: undefined, state: p.state === 'needs-admin' ? 'filed' : p.state };
    } else if (a.action === 'repost' && p.state === 'needs-admin') next = { ...p, ...reset, state: 'queued', sentAt: undefined, issue: undefined, candidates: undefined, attempts: 0 };
    else if (a.action === 'confirm' && p.state === 'withdrawing') next = { ...p, ...reset, state: 'withdrawn', candidates: undefined, commentUnknown: undefined };
    if (next) put('feedbackPublications', next);
    return next;
  });
  if (!p) throw new HttpError(409, 'That public summary changed since you looked at it, or that choice doesn’t apply to it');
  if (ACTIVE.includes(p.state)) void processPublication(id);
  return status(p);
}

/** The comment exists, is on this summary's issue, was written by the token's account and ends with the triage footer. */
async function verifyTriageComment(p: Publication, id: number) {
  if (!p.issue) throw new HttpError(409, 'That summary has no issue');
  await waitForPause(p.repo).catch(() => {
    throw new HttpError(503, 'GitHub asked us to wait; try again later');
  });
  let c: { issue_url?: string; user?: { login?: string }; body?: string } | null;
  let me: string;
  try {
    c = (await github('GET', `/repos/${p.repo}/issues/comments/${id}`)) as typeof c;
    me = await botLogin();
  } catch (err) {
    if (err instanceof GitHubError && err.status === 404) throw new HttpError(400, 'No comment with that id exists');
    // A rate limit here pauses the whole queue, like any other request.
    if (err instanceof GitHubError && err.rateLimited) {
      rateLimited(p.repo, err.retryAt);
      throw new HttpError(503, 'GitHub asked us to wait; try again later');
    }
    throw new HttpError(502, safeError((err as Error).message));
  }
  if (!c?.issue_url?.endsWith(`/repos/${p.repo}/issues/${p.issue.number}`)) throw new HttpError(400, `That comment isn’t on issue #${p.issue.number}`);
  if (c.user?.login !== me || !c.body?.endsWith(TRIAGE_FOOTER)) throw new HttpError(400, 'That comment wasn’t posted by the triage step');
}

/** Public summaries waiting for an administrator, whether or not their feedback still exists. */
export function publicationsNeedingAdmin() {
  return list<Publication>('feedbackPublications')
    .filter((p) => attentionKind(p))
    .sort((a, b) => a.createdAt.localeCompare(b.createdAt))
    .map((p) => ({
      id: p.id,
      kind: attentionKind(p)!,
      ref: attentionRef(p),
      state: p.state,
      summary: p.summary,
      repo: p.repo,
      marker: marker(p.pubId),
      issue: p.issue,
      candidates: p.candidates ?? [],
      reason:
        attentionKind(p) === 'comment-unknown'
          ? `A triage comment may have been posted on issue #${p.issue?.number} without its id being recorded. Find it on the issue and record its id, or confirm there is none. It is never posted again on its own.`
          : attentionKind(p) === 'triage-parked'
            ? `Taken out of the triage queue: ${p.triageParked!.reason}. Put it back once that's fixed, or triage it by hand.`
            : p.lastError,
      feedbackDeleted: !get('feedback', p.id),
      createdAt: p.createdAt,
    }));
}

/* ------------------------------- triage --------------------------------- */

export interface TriageDecision {
  kind: (typeof TRIAGE_KINDS)[number];
  size: (typeof TRIAGE_SIZES)[number];
  needsJesse: boolean;
  possibleDuplicateOf?: number;
  comment: string;
}

export const TRIAGE_NEUTRAL = 'Flagged for the maintainer to review.';
/** Decisions the routine may make in any rolling hour (one run's worth). */
export const TRIAGE_PER_HOUR = 10;
/** Long enough for every request of one triage (each times out after 15 s). */
const TRIAGE_LEASE_MS = 5 * 60_000;
/** A shorter triage token is refused, so a guessable one never switches triage on. */
export const TRIAGE_TOKEN_MIN = 32;

export function triageEnabled() {
  return issuesEnabled() && (config.feedbackIssues.triageToken?.length ?? 0) >= TRIAGE_TOKEN_MIN;
}

export function triageTokenMatches(header: string | undefined) {
  const want = config.feedbackIssues.triageToken;
  const got = header?.match(/^Bearer (.+)$/)?.[1];
  if (!want || !got) return false;
  return timingSafeEqual(Buffer.from(sha(got)), Buffer.from(sha(want)));
}

const triageable = (p: Publication) => p.state === 'filed' && !!p.issue && p.repo === config.feedbackIssues.repo && !!get('feedback', p.id);

/** What the routine may triage: the ten oldest filed summaries not yet triaged, and the triaged ones for spotting duplicates. */
export function triageQueue() {
  const filed = list<Publication>('feedbackPublications')
    .filter(triageable)
    .sort((a, b) => a.createdAt.localeCompare(b.createdAt));
  const row = (p: Publication) => ({ issue: p.issue!.number, url: p.issue!.url, summary: p.summary, createdAt: p.createdAt, ...(p.decision && !p.triagedAt ? { savedDecision: p.decision } : {}) });
  return {
    pending: filed.filter((p) => !p.triagedAt && !p.commentUnknown && !p.triageParked).slice(0, 10).map(row),
    triaged: filed.filter((p) => p.triagedAt).slice(-100).map(row),
  };
}

function parseTriage(b: Record<string, unknown>, issue: number): TriageDecision {
  const kind = TRIAGE_KINDS.find((k) => k === b.kind);
  const size = TRIAGE_SIZES.find((k) => k === b.size);
  if (!kind || !size) throw new HttpError(400, `kind must be one of ${TRIAGE_KINDS.join(', ')} and size one of ${TRIAGE_SIZES.join(', ')}`);
  if (b.needsJesse !== undefined && typeof b.needsJesse !== 'boolean') throw new HttpError(400, 'needsJesse must be true or false');
  const needsJesse = b.needsJesse === true;
  const dup = b.possibleDuplicateOf;
  if (dup !== undefined) {
    if (!validId(dup) || dup === issue) throw new HttpError(400, 'possibleDuplicateOf must be another issue’s number');
  }
  const comment = b.comment;
  if (needsJesse && comment !== TRIAGE_NEUTRAL) throw new HttpError(400, `When needsJesse is true the comment must be exactly “${TRIAGE_NEUTRAL}”`);
  // Same rules as testers' summaries: no links, email addresses or @mentions, at most 500 characters. It's escaped as well.
  if (typeof comment !== 'string' || !comment.trim() || publicSummary(comment) !== comment) throw new HttpError(400, 'comment must be short plain text with no links, email addresses or @mentions');
  return { kind, size, needsJesse, possibleDuplicateOf: dup as number | undefined, comment };
}

const sameDecision = (a: TriageDecision, b: TriageDecision) =>
  a.kind === b.kind && a.size === b.size && a.needsJesse === b.needsJesse && a.possibleDuplicateOf === b.possibleDuplicateOf && a.comment === b.comment;

export const triageComment = (d: TriageDecision) => `${escapeMarkdown(d.comment)}${d.possibleDuplicateOf ? `\n\nPossibly a duplicate of #${d.possibleDuplicateOf}.` : ''}${TRIAGE_FOOTER}`;

/**
 * The triage routine's only way to write: one comment and a fixed set of
 * labels on a filed summary's issue, among the ten oldest waiting.
 *
 * The decision is saved first and a retry must repeat it exactly. The comment
 * is posted at most once: if its outcome is unknown (a lost or malformed
 * answer, or a worker that vanished mid-POST), it is never posted again and a
 * withdrawal goes to an administrator. Before every request the server checks
 * the summary is still filed, its feedback still exists and the queue isn't
 * paused, and a withdrawal waits until the triage stops.
 */
export async function triagePublication(issueNumber: number, body: Record<string, unknown>) {
  // {"resume": true} carries out the decision already saved for this issue (the queue shows it).
  const input = body.resume === true ? undefined : parseTriage(body, issueNumber);
  const repo = config.feedbackIssues.repo;
  const claim = randomBytes(12).toString('hex');
  const pub = transaction(() => {
    const p = list<Publication>('feedbackPublications').find((x) => x.repo === repo && x.issue?.number === issueNumber);
    if (!p || !triageable(p)) throw new HttpError(409, 'That issue is not a filed feedback summary');
    if (p.triagedAt) throw new HttpError(409, 'That issue has already been triaged');
    if (p.triage?.phase === 'commenting' && p.triage.until <= now()) {
      // A worker vanished while posting the comment: it may exist, so it is never posted again.
      put('feedbackPublications', { ...p, triage: undefined, commentUnknown: uncertainty() });
      return undefined;
    }
    if (p.commentUnknown) throw new HttpError(409, 'A comment on that issue may have been posted without being recorded; triage it by hand');
    if (p.triage && p.triage.until > now()) throw new HttpError(409, 'That issue is being triaged');
    if (p.triageParked) throw new HttpError(409, 'That issue was taken out of the triage queue');
    if (!input && !p.decision) throw new HttpError(409, 'No decision is saved for that issue; send one');
    if (p.decision && input && !sameDecision(p.decision, input)) throw new HttpError(409, 'A different decision is already recorded for that issue; send {"resume": true} to carry it out');
    if (!p.decision) {
      if (!triageQueue().pending.some((x) => x.issue === issueNumber)) throw new HttpError(409, 'Triage the oldest summaries first, as listed in the queue');
      // Checked for a new decision only: a saved one is carried out even if its target was withdrawn since.
      if (input!.possibleDuplicateOf && !triageQueue().triaged.some((t) => t.issue === input!.possibleDuplicateOf)) throw new HttpError(400, 'possibleDuplicateOf must be a triaged feedback summary from the queue');
      if (triageSlotsUsed(repo) >= TRIAGE_PER_HOUR) throw new HttpError(429, `At most ${TRIAGE_PER_HOUR} decisions an hour`);
    }
    if (pauseOf(repo).until > now()) throw new HttpError(503, 'GitHub asked us to wait; try again later');
    const next: Publication = { ...p, triage: { claim, until: now() + TRIAGE_LEASE_MS, phase: p.comments?.length ? 'labelling' : 'commenting' } };
    put('feedbackPublications', next);
    return next;
  });
  if (!pub) throw new HttpError(409, 'A comment on that issue may have been posted without being recorded; triage it by hand');
  const resuming = !!pub.decision;
  const decision = pub.decision ?? input!;
  /** Before every request: still ours, still filed, feedback still there, not paused. */
  const check = async () => {
    const p = get<Publication>('feedbackPublications', pub.id);
    if (!p || p.triage?.claim !== claim) throw new HttpError(409, 'The triage lease ran out');
    if (!triageable(p)) throw new HttpError(409, 'The tester withdrew this summary');
    await waitForPause(repo);
  };
  const release = (change: (p: Publication) => Partial<Publication> = () => ({})) =>
    transaction(() => {
      const p = get<Publication>('feedbackPublications', pub.id);
      if (p?.triage?.claim === claim) put('feedbackPublications', { ...p, triage: undefined, ...change(p) });
    });
  let commenting = false;
  try {
    const names = await issueLabels(repo, issueNumber, check);
    // A resumed decision may already have removed needs-triage; a new one needs both labels.
    const why = !names ? 'the issue is closed' : !names.includes('feedback') ? 'the issue is no longer labelled feedback' : !resuming && !names.includes('needs-triage') ? 'the issue is no longer labelled needs-triage' : undefined;
    if (why) {
      // Out of the queue, so it can't hold a place among the oldest ten; an administrator can put it back.
      release(() => ({ triageParked: { reason: why, at: new Date(now()).toISOString() } }));
      throw new HttpError(409, `Not triaged: ${why}`);
    }
    if (!resuming) {
      // The decision is saved, and counted, before anything is written.
      const saved = transaction(() => {
        const p = get<Publication>('feedbackPublications', pub.id);
        if (!p || p.triage?.claim !== claim) return 'lease';
        const t = now();
        const recent = (get<Kv<number[]>>('kv', triageRateId(repo))?.value ?? []).filter((x) => x > t - HOUR_MS);
        if (recent.length >= TRIAGE_PER_HOUR) return 'full';
        put('kv', { id: triageRateId(repo), value: [...recent, t] });
        put('feedbackPublications', { ...p, decision });
        return 'ok';
      });
      if (saved === 'lease') throw new HttpError(409, 'The triage lease ran out');
      if (saved === 'full') throw new HttpError(429, `At most ${TRIAGE_PER_HOUR} decisions an hour`);
    }
    if (pub.triage!.phase === 'commenting') {
      await check();
      commenting = true;
      const created = (await github('POST', `/repos/${repo}/issues/${issueNumber}/comments`, { body: triageComment(decision) })) as { id?: unknown } | null;
      if (!validId(created?.id)) throw new GitHubError('GitHub’s answer had no comment id', true);
      commenting = false;
      const id = created.id;
      // Recorded even if the lease is gone, so a withdrawal can delete it.
      const ours = transaction(() => {
        const p = get<Publication>('feedbackPublications', pub.id);
        if (!p) return false;
        const mine = p.triage?.claim === claim;
        put('feedbackPublications', { ...p, comments: [...(p.comments ?? []), id], ...(mine ? { triage: { ...p.triage!, phase: 'labelling' as const } } : {}) });
        return mine;
      });
      if (!ours) throw new HttpError(409, 'The triage lease ran out');
    }
    const wanted = [decision.kind, decision.size, ...(decision.needsJesse ? ['needs-jesse'] : []), ...(decision.possibleDuplicateOf ? ['possible-duplicate'] : []), 'triaged'];
    const unwanted = (labels: string[]) => labels.filter((n) => n === 'needs-triage' || (CHOSEN_LABELS.includes(n) && !wanted.includes(n)));
    for (const name of unwanted(names!).filter((n) => n !== 'needs-triage')) await removeLabel(repo, issueNumber, name, check);
    await check();
    await github('POST', `/repos/${repo}/issues/${issueNumber}/labels`, { labels: wanted });
    await removeLabel(repo, issueNumber, 'needs-triage', check);
    // Check the labels as they are now (someone may have changed them meanwhile), tidying once if needed.
    for (let pass = 0; ; pass++) {
      const final = await issueLabels(repo, issueNumber, check);
      if (!final) throw new HttpError(409, 'The issue was closed during triage');
      const extra = unwanted(final);
      const missing = wanted.filter((l) => !final.includes(l));
      if (!extra.length && !missing.length) break;
      if (pass === 1) throw new HttpError(502, 'The issue’s labels didn’t come out as expected; try again');
      for (const name of extra) await removeLabel(repo, issueNumber, name, check);
      if (missing.length) {
        await check();
        await github('POST', `/repos/${repo}/issues/${issueNumber}/labels`, { labels: missing });
      }
    }
    rateOk(repo);
    // Recorded only if the summary is still filed: a withdrawal during the last read wins.
    const done = transaction(() => {
      const p = get<Publication>('feedbackPublications', pub.id);
      if (!p || p.triage?.claim !== claim) return false;
      put('feedbackPublications', { ...p, triage: undefined, ...(triageable(p) ? { triagedAt: new Date(now()).toISOString() } : {}) });
      return triageable(p);
    });
    if (!done) throw new HttpError(409, 'The tester withdrew this summary');
    return { issue: issueNumber, labels: wanted, comments: publicationFor(pub.id)?.comments ?? [] };
  } catch (err) {
    if (err instanceof GitHubError) {
      if (err.rateLimited) rateLimited(repo, err.retryAt);
      // A comment that may have been posted without its id: never posted again; withdrawal asks an administrator.
      release((p) => ({ commentUnknown: p.commentUnknown || (commenting && err.ambiguous ? uncertainty() : undefined) }));
      throw new HttpError(err.rateLimited ? 503 : 502, safeError(err.message));
    }
    release();
    if (err instanceof Paused) throw new HttpError(503, 'GitHub asked us to wait; try again later');
    throw err;
  }
}

const triageRateId = (repo: string) => `feedback-issues:triage-rate:${repo.toLowerCase()}`;
const triageSlotsUsed = (repo: string) => (get<Kv<number[]>>('kv', triageRateId(repo))?.value ?? []).filter((x) => x > now() - HOUR_MS).length;
/** One kind and one size: any other kind or size label is removed. Other labels are left alone. */
const CHOSEN_LABELS: string[] = [...TRIAGE_KINDS, ...TRIAGE_SIZES];

/** The issue's labels, or undefined if it isn't open. */
async function issueLabels(repo: string, issue: number, check: () => Promise<void>): Promise<string[] | undefined> {
  await check();
  const current = (await github('GET', `/repos/${repo}/issues/${issue}`)) as { state?: string; labels?: ({ name?: string } | string)[] } | null;
  if (current?.state !== 'open') return undefined;
  return (current.labels ?? []).map((l) => (typeof l === 'string' ? l : (l.name ?? '')));
}

/** Remove one label (already gone is fine). Returns the labels left, when GitHub says. */
async function removeLabel(repo: string, issue: number, name: string, check: () => Promise<void>): Promise<string[] | undefined> {
  await check();
  try {
    const left = (await github('DELETE', `/repos/${repo}/issues/${issue}/labels/${encodeURIComponent(name)}`)) as { name?: string }[] | undefined;
    return Array.isArray(left) ? left.map((l) => l.name ?? '') : undefined;
  } catch (err) {
    if (err instanceof GitHubError && err.status === 404) return undefined;
    throw err;
  }
}

