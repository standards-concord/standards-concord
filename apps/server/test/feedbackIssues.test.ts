let seq = 0;
const submit = (summary?: string) =>
  request(app)
    .post('/api/feedback')
    .send({ pathway: 'general', answers: { general: `Private answer ${++seq}: I am Morgan Lee at Northmere Hospice` }, name: 'Morgan Lee', email: 'morgan@example.org', role: 'member', ...(summary === undefined ? {} : { publish: { summary } }) });
const withdraw = (res: request.Response, token = res.body.publication.withdrawToken) => request(app).post(`/api/feedback/${res.body.id}/publication/withdraw`).send({ token });
const later = async (ms: number) => {
  t += ms;
  await processOutstanding();
};
const stateOf = (res: request.Response) => publicationFor(res.body.id)?.state;
const triage = (issue: number, body: Record<string, unknown> = {}, token = TRIAGE_TOKEN) =>
  request(app)
    .post(`/api/feedback/triage/${issue}`)
    .set('Authorization', `Bearer ${token}`)
    .send({ kind: 'ux', size: 'size:small', comment: 'Likely location: apps/web/src/pages/Diff.tsx. Suggested next step: add colours.', ...body });
const adopt = (res: request.Response, issue: number) => resolvePublication(res.body.id, { action: 'adopt', issue });
function gate() {
  let open!: (status: number) => void;
  const hold = new Promise<number>((r) => (open = r));
  return { hold, open };
}
const until = async (cond: () => boolean) => {
  for (let i = 0; i < 200 && !cond(); i++) await new Promise((r) => setTimeout(r, 10));
};

describe('the public summary text', () => {
  it('removes links in every form, email addresses and handles, after normalising Unicode', () => {
    const out = publicSummary(
      'Mail morgan@example.org, morgan＠example.org or morgan [at] example. See https://x.y/a, //evil.example/b, www.foo.com, pods.example.org/alice/private.ttl and /people/u_7a9f/private/interview.txt. cc @priyas',
    );
    expect(out).not.toMatch(/morgan|example|evil|foo\.com|alice|u_7a9f|priyas/);
    expect(out).toContain('[email removed]');
    expect(out).toContain('[link removed]');
    expect(out).toContain('[handle removed]');
  });

  it('keeps ordinary text, case, page names and version numbers, and caps the length', () => {
    expect(publicSummary('Allow US access on the Browse page in 1.2.3')).toBe('Allow US access on the Browse page in 1.2.3');
    expect(publicSummary('x'.repeat(2000)).length).toBe(500);
  });

  it('escapes Markdown in the issue so the summary cannot add links, mentions or headings', () => {
    const body = issueBody({ pubId: 'pub_x', summary: '# Heading [click](javascript:alert) <img> **bold**' });
    expect(body).toContain('\\# Heading \\[click\\]\\(javascript\\:alert\\) \\<img\\> \\*\\*bold\\*\\*');
  });
});

