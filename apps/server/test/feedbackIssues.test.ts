/**
 * A stand-in for GitHub's issues API. `next` queues one-off behaviours for the
 * next POST: an error status, "create the issue but drop the connection", or
 * "create the issue, then wait for the test before answering".
 */
interface StubIssue {
  number: number;
  repo: string;
  title: string;
  body: string;
  labels: string[];
  state: string;
  creator: string;
  created_at: string;
  auth?: string;
}
type Behaviour =
  | { status: number; headers?: Record<string, string>; body?: string }
  | { drop: true }
  | { hold: Promise<number> }
  /** Do the work, then answer 201 with this raw body, or with a cut-off body and a dropped connection. */
  | { created: string }
  | { cutOff: true };
const BOT = 'concord-bot';
const issues: StubIssue[] = [];
const comments: { id: number; repo: string; issue: number; body: string; user: string }[] = [];
/** Comment deletions to refuse with a 502, for testing a withdrawal that stops part-way. */
let failDeletes = 0;
/** One-off behaviours for the next comment POST (same shapes as for issues). */
const nextComment: Behaviour[] = [];
/** Label additions to refuse with a 502. */
let failLabels = 0;
/** Called as labels are added or removed, for interleaving other events. */
let onLabels: (() => void) | undefined;
let onLabelDelete: ((name: string) => void) | undefined;
/** Label removals to carry out and then drop the connection on. */
let dropLabelDeletes = 0;
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const next: Behaviour[] = [];
const requests: string[] = [];
let posts = 0;
const stub = http.createServer((req, res) => {
  let data = '';
  req.on('data', (c) => (data += c));
  req.on('end', async () => {
    const url = new URL(req.url ?? '/', 'http://stub');
    requests.push(`${req.method} ${url.pathname}${url.search}`);
    const json = (status: number, body: unknown) => res.writeHead(status, { 'content-type': 'application/json' }).end(JSON.stringify(body));
    if (req.method === 'GET' && url.pathname === '/user') return json(200, { login: BOT });
    const cl = url.pathname.match(/^\/repos\/([^/]+\/[^/]+)\/issues\/(\d+)\/comments$/);
    if (cl && req.method === 'GET') {
      const page = Number(url.searchParams.get('page') ?? 1);
      const per = Math.min(100, Number(url.searchParams.get('per_page') ?? 30));
      const on = comments.filter((c) => c.repo === cl[1] && c.issue === Number(cl[2]));
      return json(200, on.slice((page - 1) * per, page * per).map((c) => ({ id: c.id, body: c.body, user: { login: c.user } })));
    }
    if (cl && req.method === 'POST') {
      const b = nextComment.shift();
      if (b && 'status' in b) return void res.writeHead(b.status, b.headers).end(b.body ?? '{}');
      const id = 1000 + comments.length + Math.floor(Math.random() * 1e6);
      comments.push({ id, repo: cl[1], issue: Number(cl[2]), body: JSON.parse(data).body, user: BOT });
      if (b && 'drop' in b) return void req.socket.destroy();
      if (b && 'created' in b) return void res.writeHead(201, { 'content-type': 'application/json' }).end(b.created);
      if (b && 'cutOff' in b) {
        res.writeHead(201, { 'content-type': 'application/json', 'content-length': '100' });
        res.write(`{"id": ${id}, "bo`);
        return void setTimeout(() => req.socket.destroy(), 10);
      }
      if (b && 'hold' in b) {
        const status = await b.hold;
        if (status !== 201) return void res.writeHead(status).end('{}');
      }
      return json(201, { id });
    }
    const lb = url.pathname.match(/^\/repos\/([^/]+\/[^/]+)\/issues\/(\d+)\/labels(?:\/([^/]+))?$/);
    if (lb) {
      const i = issues.find((x) => x.repo === lb[1] && x.number === Number(lb[2]));
      if (!i) return json(404, {});
      if (req.method === 'POST') {
        if (failLabels > 0 && failLabels--) return json(502, {});
        onLabels?.();
        i.labels = [...new Set([...i.labels, ...JSON.parse(data).labels])];
        return json(200, i.labels.map((name) => ({ name })));
      }
      if (req.method === 'DELETE' && lb[3]) {
        const name = decodeURIComponent(lb[3]);
        onLabelDelete?.(name);
        if (!i.labels.includes(name)) return json(404, {});
        i.labels = i.labels.filter((l) => l !== name);
        if (dropLabelDeletes > 0 && dropLabelDeletes--) return void req.socket.destroy();
        return json(200, i.labels.map((n) => ({ name: n })));
      }
    }
    const cd = url.pathname.match(/^\/repos\/([^/]+\/[^/]+)\/issues\/comments\/(\d+)$/);
    if (cd && req.method === 'DELETE') {
      if (failDeletes > 0 && failDeletes--) return json(502, {});
      const i = comments.findIndex((c) => c.repo === cd[1] && c.id === Number(cd[2]));
      if (i < 0) return json(404, {});
      comments.splice(i, 1);
      return void res.writeHead(204).end();
    }
    const m = url.pathname.match(/^\/repos\/([^/]+\/[^/]+)\/issues(?:\/(\d+))?$/);
    if (!m) return json(404, {});
    const repo = m[1];
    if (req.method === 'GET' && !m[2]) {
      // A label filter would miss issues whose label was removed: refuse to answer one.
      if (url.searchParams.has('labels')) return json(200, []);
      const creator = url.searchParams.get('creator');
      const page = Number(url.searchParams.get('page') ?? 1);
      const per = Number(url.searchParams.get('per_page') ?? 30);
      const mine = issues.filter((i) => i.repo === repo && (!creator || i.creator === creator)).sort((a, b) => b.number - a.number);
      return json(
        200,
        mine.slice((page - 1) * per, page * per).map((i) => ({ number: i.number, html_url: `https://github.com/${repo}/issues/${i.number}`, title: i.title, body: i.body, created_at: i.created_at, user: { login: i.creator } })),
      );
    }
    if (req.method === 'GET' && m[2]) {
      const i = issues.find((x) => x.repo === repo && x.number === Number(m[2]));
      return i ? json(200, { number: i.number, state: i.state, labels: i.labels.map((name) => ({ name })) }) : json(404, {});
    }
    if (req.method === 'PATCH' && m[2]) {
      const i = issues.find((x) => x.repo === repo && x.number === Number(m[2]));
      if (!i) return json(404, {});
      Object.assign(i, JSON.parse(data));
      return json(200, {});
    }
    if (req.method !== 'POST') return json(404, {});
    posts++;
    const b = next.shift();
    if (b && 'status' in b) return void res.writeHead(b.status, b.headers).end(b.body ?? '{}');
    const number = issues.length + 1;
    issues.push({ number, repo, state: 'open', creator: BOT, created_at: new Date(t).toISOString(), auth: req.headers.authorization, ...JSON.parse(data) });
    if (b && 'drop' in b) return void req.socket.destroy();
    if (b && 'created' in b) return void res.writeHead(201, { 'content-type': 'application/json' }).end(b.created);
    if (b && 'cutOff' in b) {
      res.writeHead(201, { 'content-type': 'application/json', 'content-length': '100' });
      res.write(`{"number": ${number}, "ht`);
      return void setTimeout(() => req.socket.destroy(), 10);
    }
    if (b && 'hold' in b) {
      const status = await b.hold;
      if (status !== 201) return void res.writeHead(status).end('{}');
    }
    json(201, { number, html_url: `https://github.com/${repo}/issues/${number}` });
  });
});

