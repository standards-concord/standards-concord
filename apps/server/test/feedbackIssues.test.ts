/**
 * A stand-in for GitHub's issues API. `next` queues one-off behaviours for the
 * next POST: an error status, "create the issue but drop the connection", or
 * "create the issue, then wait for the test before answering".
 */
interface StubIssue {
  number: number;
  repo: string;
  title: string;
  body: string;
  labels: string[];
  state: string;
  creator: string;
  created_at: string;
  auth?: string;
}
type Behaviour = { status: number; headers?: Record<string, string> } | { drop: true } | { hold: Promise<number> };
const BOT = 'concord-bot';
const issues: StubIssue[] = [];
const comments: { id: number; repo: string; issue: number; body: string }[] = [];
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const next: Behaviour[] = [];
const requests: string[] = [];
let posts = 0;
const stub = http.createServer((req, res) => {
  let data = '';
  req.on('data', (c) => (data += c));
  req.on('end', async () => {
    const url = new URL(req.url ?? '/', 'http://stub');
    requests.push(`${req.method} ${url.pathname}${url.search}`);
    const json = (status: number, body: unknown) => res.writeHead(status, { 'content-type': 'application/json' }).end(JSON.stringify(body));
    if (req.method === 'GET' && url.pathname === '/user') return json(200, { login: BOT });
    const cl = url.pathname.match(/^\/repos\/([^/]+\/[^/]+)\/issues\/(\d+)\/comments$/);
    if (cl && req.method === 'GET') return json(200, comments.filter((c) => c.repo === cl[1] && c.issue === Number(cl[2])).map((c) => ({ id: c.id, body: c.body })));
    const cd = url.pathname.match(/^\/repos\/([^/]+\/[^/]+)\/issues\/comments\/(\d+)$/);
    if (cd && req.method === 'DELETE') {
      const i = comments.findIndex((c) => c.repo === cd[1] && c.id === Number(cd[2]));
      if (i < 0) return json(404, {});
      comments.splice(i, 1);
      return void res.writeHead(204).end();
    }
    const m = url.pathname.match(/^\/repos\/([^/]+\/[^/]+)\/issues(?:\/(\d+))?$/);
    if (!m) return json(404, {});
    const repo = m[1];
    if (req.method === 'GET' && !m[2]) {
      // A label filter would miss issues whose label was removed: refuse to answer one.
      if (url.searchParams.has('labels')) return json(200, []);
      const creator = url.searchParams.get('creator');
      const page = Number(url.searchParams.get('page') ?? 1);
      const per = Number(url.searchParams.get('per_page') ?? 30);
      const mine = issues.filter((i) => i.repo === repo && (!creator || i.creator === creator)).sort((a, b) => b.number - a.number);
      return json(
        200,
        mine.slice((page - 1) * per, page * per).map((i) => ({ number: i.number, html_url: `https://github.com/${repo}/issues/${i.number}`, title: i.title, body: i.body, created_at: i.created_at, user: { login: i.creator } })),
      );
    }
    if (req.method === 'PATCH' && m[2]) {
      const i = issues.find((x) => x.repo === repo && x.number === Number(m[2]));
      if (!i) return json(404, {});
      Object.assign(i, JSON.parse(data));
      return json(200, {});
    }
    if (req.method !== 'POST') return json(404, {});
    posts++;
    const b = next.shift();
    if (b && 'status' in b) return void res.writeHead(b.status, b.headers).end('{}');
    const number = issues.length + 1;
    issues.push({ number, repo, state: 'open', creator: BOT, created_at: new Date(t).toISOString(), auth: req.headers.authorization, ...JSON.parse(data) });
    if (b && 'drop' in b) return void req.socket.destroy();
    if (b && 'hold' in b) {
      const status = await b.hold;
      if (status !== 201) return void res.writeHead(status).end('{}');
    }
    json(201, { number, html_url: `https://github.com/${repo}/issues/${number}` });
  });
});

