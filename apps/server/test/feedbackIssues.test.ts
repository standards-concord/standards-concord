let seq = 0;
const submit = (summary?: string) =>
  request(app)
    .post('/api/feedback')
    .send({ pathway: 'general', answers: { general: `Private answer ${++seq}: I am Morgan Lee at Northmere Hospice` }, name: 'Morgan Lee', email: 'morgan@example.org', role: 'member', ...(summary === undefined ? {} : { publish: { summary } }) });
const withdraw = (res: request.Response, token = res.body.publication.withdrawToken) => request(app).post(`/api/feedback/${res.body.id}/publication/withdraw`).send({ token });
const later = async (ms: number) => {
  t += ms;
  await processOutstanding();
};
const stateOf = (res: request.Response) => publicationFor(res.body.id)?.state;
function gate() {
  let open!: (status: number) => void;
  const hold = new Promise<number>((r) => (open = r));
  return { hold, open };
}
const until = async (cond: () => boolean) => {
  for (let i = 0; i < 200 && !cond(); i++) await new Promise((r) => setTimeout(r, 10));
};

describe('the public summary text', () => {
  it('removes links in every form, email addresses and handles, after normalising Unicode', () => {
    const out = publicSummary(
      'Mail morgan@example.org, morgan＠example.org or morgan [at] example. See https://x.y/a, //evil.example/b, www.foo.com, pods.example.org/alice/private.ttl and /people/u_7a9f/private/interview.txt. cc @priyas',
    );
    expect(out).not.toMatch(/morgan|example|evil|foo\.com|alice|u_7a9f|priyas/);
    expect(out).toContain('[email removed]');
    expect(out).toContain('[link removed]');
    expect(out).toContain('[handle removed]');
  });

  it('keeps ordinary text, case, page names and version numbers, and caps the length', () => {
    expect(publicSummary('Allow US access on the Browse page in 1.2.3')).toBe('Allow US access on the Browse page in 1.2.3');
    expect(publicSummary('x'.repeat(2000)).length).toBe(500);
  });

  it('escapes Markdown in the issue so the summary cannot add links, mentions or headings', () => {
    const body = issueBody({ pubId: 'pub_x', summary: '# Heading [click](javascript:alert) <img> **bold**' });
    expect(body).toContain('\\# Heading \\[click\\]\\(javascript:alert\\) \\<img\\> \\*\\*bold\\*\\*');
  });
});

describe('opting in', () => {
  it('posts nothing without the tester’s opt-in', async () => {
    const res = await submit();
    expect(res.status).toBe(201);
    expect(res.body.publication).toBeUndefined();
    await processOutstanding();
    expect(posts).toBe(0);
  });

  it('refuses to post when the option is switched off, before storing anything', async () => {
    config.feedbackIssues.token = undefined;
    expect((await request(app).get('/api/feedback/publishing')).body.enabled).toBe(false);
    const before = list('feedback').length;
    expect((await submit('The diff view needs colours')).status).toBe(409);
    expect(list('feedback').length).toBe(before);
  });

  it('refuses a summary that is not exactly what the preview showed', async () => {
    expect((await submit('Email me at morgan@example.org')).status).toBe(400);
    expect(posts).toBe(0);
  });

  it('posts only the summary, with a random publication id and none of the answers or metadata', async () => {
    const res = await submit('The diff view needs colours');
    expect(res.status).toBe(201);
    expect(res.body.publication).toMatchObject({ state: 'filed', issue: { number: 1 } });
    expect(res.body.publication.withdrawToken).toMatch(/^[\w-]{20,}$/);
    const [issue] = issues;
    expect(issue.auth).toBe('Bearer test-token-not-real');
    expect(issue.labels).toEqual(['feedback', 'needs-triage']);
    expect(issue.title).toBe('Feedback: The diff view needs colours');
    const published = `${issue.title}\n${issue.body}`;
    expect(published).toContain('> The diff view needs colours');
    expect(published).not.toContain(res.body.id);
    expect(published).toMatch(/concord-feedback-publication: pub_/);
    expect(published).not.toMatch(/Morgan|Northmere|example\.org|member|general|Private answer|2026/);
  });

  it('files each submission as its own issue with its own exact text', async () => {
    await Promise.all([submit('Allow US access'), submit('allow us access')]);
    expect(issues.map((i) => i.title).sort()).toEqual(['Feedback: Allow US access', 'Feedback: allow us access']);
  });
});

describe('delivery', () => {
  it('holds summaries past the hourly cap and posts them as the rolling hour frees up', async () => {
    config.feedbackIssues.perHour = 1;
    await submit('Cap one');
    t += 30 * 60_000;
    const held = await submit('Cap two');
    expect(held.body.publication.state).toBe('queued');
    await later(20 * 60_000);
    expect(posts).toBe(1);
    await later(11 * 60_000);
    expect(issues.map((i) => i.title)).toEqual(['Feedback: Cap one', 'Feedback: Cap two']);
  });

  it('keeps the cap in the database, per repository', async () => {
    config.feedbackIssues.perHour = 1;
    await submit('Cap shared one');
    expect(get<{ value: number[] }>('kv', `feedback-issues:rate:${REPO}`)?.value).toHaveLength(1);
    resetFeedbackIssueState(); // as if another process
    await submit('Cap shared two');
    expect(posts).toBe(1);
  });

  it('honours Retry-After by pausing the whole queue', async () => {
    next.push({ status: 429, headers: { 'retry-after': '3600' } });
    const first = await submit('Rate limited one');
    expect(first.body.publication.state).toBe('queued');
    await submit('Rate limited two');
    await later(30 * 60_000);
    expect(posts).toBe(1);
    await later(31 * 60_000);
    expect(issues.map((i) => i.title).sort()).toEqual(['Feedback: Rate limited one', 'Feedback: Rate limited two']);
  });

  it('honours the rate-limit reset time on a 403', async () => {
    next.push({ status: 403, headers: { 'x-ratelimit-remaining': '0', 'x-ratelimit-reset': String(Math.ceil((t + 2 * HOUR) / 1000)) } });
    await submit('Secondary limit');
    await later(HOUR);
    expect(posts).toBe(1);
    await later(HOUR + 1000);
    expect(issues).toHaveLength(1);
  });

  it('backs off exponentially on 429s that give no time', async () => {
    next.push({ status: 429 }, { status: 429 }, { status: 429 });
    const res = await submit('Headerless limits');
    const pause = () => get<{ value: { until: number; streak: number } }>('kv', `feedback-issues:pause:${REPO}`)!.value;
    expect(pause()).toEqual({ until: t + 60_000, streak: 1 });
    await later(60_000);
    expect(pause()).toEqual({ until: t + 2 * 60_000, streak: 2 });
    await later(2 * 60_000);
    expect(pause()).toEqual({ until: t + 4 * 60_000, streak: 3 });
    await later(4 * 60_000);
    expect(stateOf(res)).toBe('filed');
    expect(pause().streak).toBe(0);
  });

  it('checks the pause before every request, including searches', async () => {
    next.push({ drop: true });
    const res = await submit('Paused search');
    expect(stateOf(res)).toBe('unknown');
    put('kv', { id: `feedback-issues:pause:${REPO}`, value: { until: t + 3 * HOUR, streak: 1 } });
    requests.length = 0;
    await later(HOUR);
    expect(requests).toEqual([]);
  });

  it('finds the issue instead of posting again when GitHub’s answer was lost, even without its label', async () => {
    next.push({ drop: true });
    const res = await submit('Lost answer');
    expect(res.body.publication.state).toBe('unknown');
    issues[0].labels = [];
    await later(HOUR);
    expect(posts).toBe(1);
    expect(publicationFor(res.body.id)).toMatchObject({ state: 'filed', issue: { number: 1 } });
    expect(requests.some((r) => r.includes('labels='))).toBe(false);
  });

  it('never posts again on its own when the outcome stays unknown, and waits for an administrator', async () => {
    next.push({ drop: true });
    const res = await submit('Maybe posted');
    issues.length = 0; // GitHub didn't keep it after all
    for (let i = 0; i < MAX_MISSES + 1; i++) await later(7 * HOUR);
    expect(posts).toBe(1);
    expect(stateOf(res)).toBe('needs-admin');
    resolvePublication(res.body.id, 'repost');
    await processPublication(res.body.id);
    expect(stateOf(res)).toBe('filed');
    expect(posts).toBe(2);
  });

  it('only trusts its own account’s issues whose marker, title and body all match', async () => {
    next.push({ drop: true });
    const res = await submit('Copied marker');
    const mine = issues.pop()!;
    // Someone else copies the whole issue; the bot has another issue with the marker but changed text.
    issues.push({ ...mine, number: 1, creator: 'someone-else' }, { ...mine, number: 2, body: `${mine.body}\nedited` });
    for (let i = 0; i < MAX_MISSES + 1; i++) await later(7 * HOUR);
    expect(stateOf(res)).toBe('needs-admin');
    expect(issues.every((i) => i.state === 'open')).toBe(true);
  });

  it('waits for an administrator when two of its own issues match', async () => {
    next.push({ drop: true });
    const res = await submit('Two matches');
    issues.push({ ...issues[0], number: 2 });
    await later(HOUR);
    expect(stateOf(res)).toBe('needs-admin');
    expect(publicationFor(res.body.id)?.lastError).toMatch(/2 matching issues/);
    expect(posts).toBe(1);
  });

  it('reconciles a send whose worker vanished once its claim runs out', async () => {
    next.push({ drop: true });
    const res = await submit('Crashed mid-send');
    const pub = publicationFor(res.body.id)!;
    put('feedbackPublications', { ...pub, state: 'sending', claim: 'gone', claimUntil: t + 60_000 });
    await processOutstanding();
    expect(stateOf(res)).toBe('sending');
    await later(HOUR);
    expect(stateOf(res)).toBe('filed');
    expect(posts).toBe(1);
  });

  it('retries definite refusals, then waits for an administrator', async () => {
    for (let i = 0; i < MAX_ATTEMPTS; i++) next.push({ status: 422 });
    const res = await submit('Keeps failing');
    for (let i = 1; i < MAX_ATTEMPTS; i++) await later(7 * HOUR);
    expect(stateOf(res)).toBe('needs-admin');
    expect(posts).toBe(MAX_ATTEMPTS);
    resolvePublication(res.body.id, 'check');
    await processPublication(res.body.id);
    expect(stateOf(res)).toBe('filed');
  });

  it('keeps the destination the tester agreed to, even if the configuration changes', async () => {
    config.feedbackIssues.perHour = 1;
    await submit('Fills the cap');
    const res = await submit('Agreed to the first repository');
    config.feedbackIssues.repo = 'someone/else';
    await later(2 * HOUR);
    expect(issues.find((i) => i.title === 'Feedback: Agreed to the first repository')?.repo).toBe(REPO);
    await withdraw(res);
    expect(issues.find((i) => i.repo === REPO && i.number === 2)?.state).toBe('closed');
    expect(requests.some((r) => r.includes('someone/else'))).toBe(false);
  });

  it('never posts a summary whose feedback was deleted, and never recreates the feedback', async () => {
    config.feedbackIssues.perHour = 1;
    await submit('Fills the cap again');
    const res = await submit('Deleted before posting');
    remove('feedback', res.body.id);
    await later(2 * HOUR);
    expect(issues).toHaveLength(1);
    expect(get('feedback', res.body.id)).toBeUndefined();
    expect(stateOf(res)).toBe('withdrawn');
  });

  it('takes back a posted summary when its feedback is deleted', async () => {
    const res = await submit('Deleted after posting');
    remove('feedback', res.body.id);
    await later(60_000);
    expect(issues[0].state).toBe('closed');
    expect(stateOf(res)).toBe('withdrawn');
  });

  it('never logs the token', async () => {
    const warn = console.warn;
    const lines: string[] = [];
    console.warn = (...a: unknown[]) => void lines.push(a.join(' '));
    const realFetch = globalThis.fetch;
    globalThis.fetch = (async () => {
      throw new Error('bad credentials test-token-not-real');
    }) as typeof fetch;
    try {
      await submit('Token leak check');
    } finally {
      globalThis.fetch = realFetch;
      console.warn = warn;
    }
    expect(lines.join('\n')).toContain('public summary');
    expect(lines.join('\n')).not.toContain('test-token-not-real');
  });
});

describe('withdrawing', () => {
  it('needs the token from the submission', async () => {
    const res = await submit('Withdraw needs token');
    expect((await withdraw(res, 'guess')).status).toBe(403);
  });

  it('stops a queued summary from ever being posted', async () => {
    config.feedbackIssues.perHour = 1;
    await submit('Fills the cap too');
    const res = await submit('Changed my mind');
    expect((await withdraw(res)).body.state).toBe('withdrawn');
    await later(2 * HOUR);
    expect(issues.map((i) => i.title)).toEqual(['Feedback: Fills the cap too']);
  });

  it('replaces a posted summary and closes its issue', async () => {
    const res = await submit('Posted then withdrawn');
    expect((await withdraw(res)).body.state).toBe('withdrawn');
    expect(issues[0]).toMatchObject({ title: 'Withdrawn feedback', body: 'The tester withdrew this feedback.', state: 'closed' });
  });

  it('deletes the triage comments on a withdrawn issue, and keeps other people’s', async () => {
    const res = await submit('Withdrawn with comments');
    comments.push({ id: 1, repo: REPO, issue: 1, body: `Likely in apps/web/src/pages/Diff.tsx.${FOOTER}` }, { id: 2, repo: REPO, issue: 1, body: 'A maintainer’s note' });
    expect((await withdraw(res)).body.state).toBe('withdrawn');
    expect(comments.map((c) => c.id)).toEqual([2]);
  });

  it('for a day, deletes triage comments that raced the withdrawal', async () => {
    const res = await submit('Raced comment');
    await withdraw(res);
    comments.push({ id: 3, repo: REPO, issue: 1, body: `Posted just after.${FOOTER}` });
    await later(5 * 60_000);
    expect(comments).toHaveLength(1); // swept every 15 minutes
    await later(11 * 60_000);
    expect(comments).toHaveLength(0);
    comments.push({ id: 4, repo: REPO, issue: 1, body: `Much later.${FOOTER}` });
    await later(25 * HOUR);
    expect(comments).toHaveLength(1);
  });

  it('finds and retracts the issue when the outcome was unknown', async () => {
    next.push({ drop: true });
    const res = await submit('Withdrawn while unknown');
    expect((await withdraw(res)).body.state).toBe('withdrawn');
    expect(issues[0].state).toBe('closed');
    expect(posts).toBe(1);
  });

  it('retracts the issue when the withdrawal arrives while the POST is in flight', async () => {
    const g = gate();
    next.push({ hold: g.hold });
    // The tester is told it's still sending (the server stops waiting after a few seconds).
    const res = await submit('Withdrawn mid-send');
    expect(res.body.publication.state).toBe('sending');
    const w = withdraw(res).then((r) => r);
    await until(() => stateOf(res) === 'withdrawing');
    g.open(201);
    expect((await w).body.state).toBe('withdrawn');
    expect(issues[0]).toMatchObject({ state: 'closed', title: 'Withdrawn feedback' });
    expect(posts).toBe(1);
  });

  it('a stalled worker cannot bring back a summary that was withdrawn', async () => {
    const g = gate();
    next.push({ hold: g.hold });
    const sending = submit('Stalled worker').then((r) => r);
    await until(() => posts === 1);
    const fid = list<Publication>('feedbackPublications').find((p) => p.summary === 'Stalled worker')!.id;
    // Worker A is stuck waiting for GitHub. Its claim runs out; another process (B) takes over.
    t += 5 * 60_000;
    resetFeedbackIssueState();
    await processPublication(fid);
    expect(publicationFor(fid)?.state).toBe('filed');
    const res = await Promise.race([sending, new Promise<undefined>((r) => setTimeout(() => r(undefined), 4500))]);
    expect(res).toBeDefined();
    // The tester withdraws; B retracts the issue.
    expect((await withdraw(res!)).body.state).toBe('withdrawn');
    expect(issues[0].state).toBe('closed');
    // A finally hears back with an error: it must not change anything.
    g.open(502);
    await new Promise((r) => setTimeout(r, 50));
    expect(publicationFor(fid)?.state).toBe('withdrawn');
    await later(7 * HOUR);
    expect(posts).toBe(1);
    expect(publicationFor(fid)?.state).toBe('withdrawn');
  });

  it('withdraws a summary waiting for an administrator, retracting it if it turns out to exist', async () => {
    next.push({ drop: true });
    const res = await submit('Needs admin then withdrawn');
    const created = issues.pop()!;
    for (let i = 0; i < MAX_MISSES + 1; i++) await later(7 * HOUR);
    expect(stateOf(res)).toBe('needs-admin');
    issues.push(created); // it existed after all (GitHub's list was behind)
    expect((await withdraw(res)).body.state).toBe('withdrawn');
    expect(issues[0].state).toBe('closed');
  });

  it('keeps trying to withdraw while the search is inconclusive, and never reports success early', async () => {
    next.push({ drop: true });
    const res = await submit('Inconclusive withdrawal');
    issues.push({ ...issues[0], number: 2 });
    expect((await withdraw(res)).body.state).toBe('withdrawing');
    await later(7 * HOUR);
    expect(stateOf(res)).toBe('withdrawing');
    expect(issues.every((i) => i.state === 'open')).toBe(true);
  });
});

